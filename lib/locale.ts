export function translateCore(text: string, language: Language) {
  if (language === "ko") return text;
  return coreTranslations[normalizeText(text)]?.[language === "en" ? 0 : 1] ?? text;
}
export function matchesLocalized(value: string, query: string) {
  const normalize = (s: string) => s.toLocaleLowerCase().replace(/\s+/g, "");
  return [value, translateCore(value, "en"), translateCore(value, "ja")].some(text => normalize(text).includes(normalize(query)));
}
